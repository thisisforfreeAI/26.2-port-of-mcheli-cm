"""Rewrites fabric/neoforge-only.txt: the shared sources the Fabric build leaves out.

A file is left out when it still uses a NeoForge API that Fabric lacks. NeoForge's config classes
are fine: Forge Config API Port provides them on Fabric. Run from the repository root:
    python3 fabric/update-neoforge-only.py
"""
import pathlib
import re

ROOT = pathlib.Path('src/main/java')
# NeoForge classes that Forge Config API Port ships on Fabric under the same names.
ON_FABRIC = {
    'net.neoforged.neoforge.common.ModConfigSpec',
    'net.neoforged.fml.config.ModConfig',
    'net.neoforged.fml.config.IConfigSpec',
    'net.neoforged.neoforge.common.TranslatableEnum',
    'net.neoforged.neoforge.client.gui.ConfigurationScreen',
}
USE = re.compile(r'net\.neoforged\.[\w.]*[A-Z]\w*')

excluded = []
for path in sorted(ROOT.rglob('*.java')):
    rel = path.relative_to(ROOT).as_posix()
    if any(folder in '/' + rel for folder in ('/platform/neoforge/', '/platform/loader/', '/gametest/',
                                               '/datagen/', '/compat/hbm/NtmBridge.java',
                                               '/compat/hbm/VntProcessors.java')):
        continue  # excluded as a whole folder by fabric/build.gradle
    text = path.read_text(encoding='utf-8')
    used = {m.group(0) for m in USE.finditer(text)}
    used |= set(re.findall(r'import\s+(?:static\s+)?(net\.neoforged\.[\w.]*)\.\*', text))
    if any(not any(name == ok or name.startswith(ok + '.') or name.startswith(ok + '$') for ok in ON_FABRIC)
           for name in used):
        excluded.append(rel)

header = ('# Generated by fabric/update-neoforge-only.py: shared sources that still use NeoForge APIs\n'
          '# Fabric lacks. The list shrinks as the NeoForge glue moves behind platform/Platform.java.\n')
pathlib.Path('fabric/neoforge-only.txt').write_text(header + ''.join(f + '\n' for f in excluded), encoding='utf-8')
print(len(excluded), 'files left out of the Fabric build')
